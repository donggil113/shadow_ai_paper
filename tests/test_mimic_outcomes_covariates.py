# ------------------------------------------------------ (a) structured echo
def test_compute_structured_shd_components_and_composite():
    meas = pd.DataFrame({
        "study_id": [1, 2, 3, 4, 5, 6, 7, 8],
        "lvef": [60, 35, 60, 60, np.nan, 0.55, 58, 62],
        "ivsd": [1.0, 1.0, 14.0, 1.0, np.nan, 1.0, 1.0, 1.0],       # row 3: mm -> 1.4 cm
        "lvpwd": [0.9, 0.9, 0.9, 0.9, np.nan, 0.9, 0.9, 0.9],
        "aortic_stenosis": ["mild", "none", "none", "severe", None, "trace", "none", "none"],
        "mr_grade": ["none", "none", "none", "none", None, "none", "moderate to severe", "mild-to-moderate"],
        "tr_vmax": [2.5, 2.5, 2.5, 2.5, np.nan, 2.5, 2.5, 3.4],
        "rvsp": [30, 30, 30, 30, np.nan, 30, 30, 50],
    })
    out = outc.compute_structured_shd(meas)
    assert list(out.columns) == COMPONENTS + ["shd_echo_struct", "n_components_evaluated"]
    assert len(out) == len(meas)
    shd = out["shd_echo_struct"].tolist()
    assert shd[0] == 0.0                                    # everything below threshold
    assert shd[1] == 1.0 and out.loc[1, "lvef_lte_45"] == 1.0
    assert shd[2] == 1.0 and out.loc[2, "lvwt_gte_13"] == 1.0   # 14 mm -> 1.4 cm >= 1.3
    assert shd[3] == 1.0 and out.loc[3, "aortic_stenosis_moderate_severe"] == 1.0
    assert np.isnan(shd[4]) and out.loc[4, "n_components_evaluated"] == 0
    assert shd[5] == 0.0 and out.loc[5, "lvef_lte_45"] == 0.0   # fraction 0.55 -> 55 %
    assert shd[6] == 1.0 and out.loc[6, "mitral_regurgitation_moderate_severe"] == 1.0
    assert out.loc[7, "mitral_regurgitation_moderate_severe"] == 0.0   # mild-to-moderate < moderate
    assert out.loc[7, "tr_max_gte_32"] == 1.0 and out.loc[7, "pasp_gte_45"] == 1.0 and shd[7] == 1.0
    # components never measured stay NaN, evaluated ones are counted
    assert out["pericardial_effusion_moderate_large"].isna().all()
    assert out.loc[0, "n_components_evaluated"] == 6
    # explicit column map overrides alias matching
    out2 = outc.compute_structured_shd(meas.rename(columns={"lvef": "weird"}), column_map={"lvef": "weird"})
    assert out2["lvef_lte_45"].tolist()[:2] == [0.0, 1.0]


