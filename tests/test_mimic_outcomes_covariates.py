def test_label_from_icd_sources_and_priority():
    rec = _records()
    ecg_icd = pd.DataFrame({"study_id": [1, 2], "all_diag_all": ["['I5023', 'E119']", "['E119', 'J189']"]})
    adm = pd.DataFrame({
        "subject_id": [S + 3, S + 4], "hadm_id": [10, 11],
        "admittime": pd.to_datetime(["2018-03-01", "2018-04-01"]),
        "dischtime": pd.to_datetime(["2018-03-05", "2018-04-05"]),
    })
    dx = pd.DataFrame({"subject_id": [S + 3, S + 3, S + 4], "hadm_id": [10, 10, 11],
                       "icd_code": ["I35.0", "E119", "4280"], "icd_version": [10, 10, 9]})
    out = outc.label_from_icd(rec, dx, ecg_icd, adm)
    assert out["Y_icd"].tolist()[:3] == [1.0, 0.0, 1.0] and np.isnan(out["Y_icd"].iloc[3])
    assert out["icd_source"].tolist() == ["mimic_ecg_icd", "mimic_ecg_icd", "hosp_admission",
                                          "hosp_admission_icd9_only"]
    assert out["icd_matched"].tolist()[:3] == ["I5023", "", "I350"]      # dots removed
    assert out["icd_hadm_id"].iloc[2] == 10
    with pytest.raises(ValueError):
        outc.label_from_icd(rec, None, None, None)
    # hosp route alone, without the ECG-ICD table
    out2 = outc.label_from_icd(rec, dx, None, adm)
    assert np.isnan(out2["Y_icd"].iloc[0]) and out2["icd_source"].iloc[0] == "none"
    assert out2["Y_icd"].iloc[2] == 1.0


def test_icd_circularity_diagnostic():
    y = np.array([1, 0, 1, np.nan, 0, 1, 0, 0])
    T = np.array([1, 1, 1, 1, 0, 0, 0, 0])
    linked = np.array([True, True, True, True, False, True, False, False])
    d = outc.icd_circularity_diagnostic(y, T, linked)
    assert d["n"] == 8 and d["n_assessable"] == 7
    t1, t0 = d["icd_rate_by_T"]["T1"], d["icd_rate_by_T"]["T0"]
    assert t1["n"] == 3 and t1["n_pos"] == 2 and t1["rate"] == pytest.approx(2 / 3)
    assert t0["n"] == 4 and t0["n_pos"] == 1 and t0["rate"] == pytest.approx(0.25)
    assert d["icd_rate_by_T"]["risk_ratio"] == pytest.approx((2 / 3) / 0.25)
    assert d["icd_rate_by_T"]["risk_difference"] == pytest.approx(2 / 3 - 0.25)
    lo, hi = t1["ci95"]
    assert 0.0 <= lo < t1["rate"] < hi <= 1.0                      # Wilson interval
    e = d["icd_rate_by_echo_linked"]
    assert e["linked"]["n"] == 4 and e["not_linked"]["n"] == 3
    assert outc.icd_circularity_diagnostic(y, T)["icd_rate_by_echo_linked"] is None
    with pytest.raises(ValueError):
        outc.icd_circularity_diagnostic(y, T[:-1])


