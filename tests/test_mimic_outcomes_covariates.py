def test_assert_no_forbidden():
    for bad in ("Y_note", "T", "Z", "lvef_mean", "nearest_echo_days", "careunit", "dischtime",
                "study_id", "shd", "note_confidence", "icd_matched", "echo_time", "days_to_nearest_echo"):
        with pytest.raises(cov.ForbiddenFeatureError):
            cov.assert_no_forbidden(["age_at_ecg", bad])
        assert cov.is_forbidden(bad) is not None
    good = ["age_at_ecg", "sex_male", "lab_troponin", "lab_troponin_missing", "ecg_rr", "ecg_qtc",
            "setting_ed", "ecg_emb_001", "tabular_x"]
    cov.assert_no_forbidden(good)                                   # no raise
    assert all(cov.is_forbidden(g) is None for g in good)
    assert issubclass(cov.ForbiddenFeatureError, AssertionError)


def test_assemble_X_shapes_and_imputation():
    idx = pd.RangeIndex(6)
    a = pd.DataFrame({"age_at_ecg": [50, 60, np.nan, 70, 80, 90], "sex_male": [1, 0, 1, np.nan, 0, 1]}, index=idx)
    b = pd.DataFrame({"lab_bnp": [np.nan] * 6, "ecg_rr": [800, 900, 1000, np.nan, 700, 750]}, index=idx)
    train = np.array([True, True, True, False, False, False])
    with pytest.warns(UserWarning):                                  # lab_bnp all-NaN on train -> 0
        X, names, imp = cov.assemble_X({"demo": a, "rest": b}, train)
    assert X.shape == (6, 4) and names == ["age_at_ecg", "sex_male", "lab_bnp", "ecg_rr"]
    assert not np.isnan(X).any()
    assert X[2, 0] == 55.0                    # median of the TRAIN rows (50, 60), not of all rows
    assert X[3, 3] == 900.0                   # train median of ecg_rr (800, 900, 1000)
    assert (X[:, 2] == 0.0).all()
    X2, _, _ = cov.assemble_X({"demo": a, "rest": b}, train, imputer=imp)
    assert np.array_equal(X, X2)
    with pytest.raises(cov.ForbiddenFeatureError):
        cov.assemble_X({"demo": a, "bad": pd.DataFrame({"Y_note": np.zeros(6)}, index=idx)}, train)
    with pytest.raises(ValueError):
        cov.assemble_X({"demo": a, "b": b.iloc[:5]}, train)
    with pytest.raises(ValueError):
        cov.assemble_X({"demo": a}, np.zeros(6, dtype=bool))
    with pytest.raises(TypeError):
        cov.assemble_X({"demo": a.assign(sex_male=["M"] * 6)}, train)


