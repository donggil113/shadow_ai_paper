def test_covariate_blocks_on_fixture(fx):
    rec = fx["records"]
    blocks = cov.covariate_blocks(rec, patients=fx["patients"], labevents=fx["labevents"],
                                  d_labitems=fx["d_labitems"], edstays=fx["edstays"],
                                  admissions=fx["admissions"], machine_measurements=fx["machine_measurements"],
                                  verbose=False)
    assert set(blocks) == {"demographics", "labs", "setting", "ecg_tabular"}
    n = len(rec)
    assert blocks["demographics"].shape == (n, 2) and blocks["labs"].shape == (n, 8)
    assert blocks["setting"].shape == (n, 3) and blocks["ecg_tabular"].shape == (n, 8)
    for b in blocks.values():
        assert b.index.equals(rec.index)
        cov.assert_no_forbidden(b.columns)
    assert (blocks["setting"].sum(axis=1) == 1.0).all()
    row = rec.index[rec["study_id"] == 40_000_025][0]
    assert blocks["setting"].loc[row, "setting_ed"] == 1.0            # ED stay contains the ECG
    row1 = rec.index[rec["study_id"] == 40_000_001][0]
    assert blocks["setting"].loc[row1, "setting_inpatient"] == 1.0
    # labs: subject 90000001 has haemoglobin 13.1 after the ECG, 12.4 at 30 h, 11.8 at 5 h before
    assert blocks["labs"].loc[row1, "lab_hemoglobin"] == 11.8
    assert blocks["labs"].loc[row1, "lab_hemoglobin_missing"] == 0.0
    assert blocks["labs"]["lab_troponin_missing"].sum() == n - 12
    # demographics: anchor_age + (year(ecg) - anchor_year); patients row for S1 is F, 39, 2018
    assert blocks["demographics"].loc[row1, "age_at_ecg"] == 39.0 and blocks["demographics"].loc[row1, "sex_male"] == 0.0
    # machine measurements: sentinel 29999 rows become NaN for PR and P axis only
    et = blocks["ecg_tabular"]
    sentinel = fx["machine_measurements"]["p_onset"] == 29999.0
    assert sentinel.sum() == 4 and et.loc[sentinel.to_numpy(), "ecg_pr"].isna().all()
    assert et.loc[sentinel.to_numpy(), "ecg_p_axis"].isna().all()
    assert et.loc[~sentinel.to_numpy(), ["ecg_rr", "ecg_pr", "ecg_qrs", "ecg_qt", "ecg_qtc"]].notna().all().all()
    X, names, _ = cov.assemble_X(blocks, np.ones(n, dtype=bool))
    assert X.shape == (n, 21) and len(names) == 21


def test_label_from_notes_on_fixture(fx):
    rec = fx["records"].copy()
    et = fx["echo_study_list"].set_index("study_id")["study_datetime"]
    rec["echo_time"] = pd.to_datetime(et.reindex(rec["nearest_echo_study_id"].astype("float")).to_numpy())
    rec.loc[rec["T"] != 1, "echo_time"] = pd.NaT
    out = outc.label_from_notes(rec, fx["discharge"], fx["admissions"])
    assert out.index.equals(rec.index) and set(out["Y_note"].dropna().unique()) <= {0.0, 1.0}
    r1 = out.loc[rec["study_id"] == 40_000_001].iloc[0]           # hadm 20000001 -> template 0 (LVEF 30 %)
    assert r1["Y_note"] == 1.0 and r1["note_lvef"] == 30.0 and r1["note_n_notes"] == 1
    r2 = out.loc[rec["study_id"] == 40_000_002].iloc[0]           # template 1: EF 55-60 %, negated valves
    assert r2["Y_note"] == 0.0 and r2["note_lvef"] == 57.5 and r2["note_wall_cm"] == 0.9
    s11 = out.loc[rec["subject_id"] == S + 11]                    # template 5: no cardiac work-up
    assert s11["Y_note"].isna().all() and (s11["note_n_notes"] == 1).all()
    s5 = out.loc[rec["subject_id"] == S + 5]                      # admission contains the echo
    assert (s5["note_link"] == "echo_admission").all()
    s4 = out.loc[rec["subject_id"] == S + 4]                      # no admission, no note
    assert s4["Y_note"].isna().all() and (s4["note_n_notes"] == 0).all() and (s4["note_link"] == "none").all()
