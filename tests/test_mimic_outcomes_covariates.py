# ------------------------------------------------------------- (b) notes
@pytest.mark.parametrize("text, lvef, shd, valve_c", [
    ("TTE showed LVEF 30% with global hypokinesis.", 30.0, 1, None),
    ("Echo: EF 55-60%, no evidence of moderate or severe AS or MR.", 57.5, 0, False),   # negated
    ("Severe aortic stenosis was noted on echocardiogram; EF preserved.", None, 1, True),
    ("Echo: no LVH. Normal LVEF. Mild MR.", None, 0, False),                            # negated LVH
    ("Patient has a history of multiple sclerosis (MS); admitted for cellulitis.", None, None, None),
    ("IVSd 1.5 cm, LVPWd 1.4 cm, EF 60%.", 60.0, 1, None),
    ("Echo without significant mitral regurgitation, EF 65%.", 65.0, 0, False),          # negated
])
def test_regex_extraction_sentences(text, lvef, shd, valve_c):
    r = extract_note(text)
    assert r["lvef"] == lvef
    assert r["shd_composite"] == shd
    assert r["components"]["valve_moderate_or_severe"] is valve_c
    assert r["extractor"] == "regex"


def test_regex_extraction_details():
    r = extract_note("Echo: EF 55-60%, no evidence of moderate or severe AS or MR.")
    assert r["components"]["lvef_le_45"] is False
    assert [(v["valve"], v["severity"], v["negated"]) for v in r["valve_lesions"]] == [("AS", "none", True)]
    r = extract_note("Echo without significant mitral regurgitation, EF 65%.")
    assert r["valve_lesions"][0]["valve"] == "MR" and r["valve_lesions"][0]["negated"] is True
    r = extract_note("Echo: no LVH. Normal LVEF. Mild MR.")
    assert r["lvh_negated"] is True and r["components"]["wall_ge_1p3"] is False
    assert r["lvef_qualitative"] == "normal"
    r = extract_note("IVSd 1.5 cm, LVPWd 1.4 cm, EF 60%.")
    assert r["wall_thickness_cm"] == 1.5 and r["septal_cm"] == 1.5 and r["posterior_cm"] == 1.4
    r = extract_note("Echocardiogram showed moderate concentric LVH and moderate to severe mitral "
                     "regurgitation; LVEF 55%.")
    assert r["lvh_qualitative"] == "moderate" and r["components"]["wall_ge_1p3"] is True
    assert r["valve_lesions"][0]["severity"] == "moderate_severe" and r["shd_composite"] == 1
    assert 0.0 < r["confidence"] <= 1.0
    e = extract_note("")
    assert e["shd_composite"] is None and e["n_fields_found"] == 0 and e["confidence"] == 0.0


