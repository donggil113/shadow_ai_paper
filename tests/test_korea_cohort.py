def test_analyze_containment(analysis):
    c = analysis["containment"]
    assert c["available"] is True
    assert c["batch_cohort_outcome_observed_all"] is True and c["T_all_one"] is False
    assert isinstance(c["contains_point"], bool)
    assert isinstance(c["contains_ci"], bool) and isinstance(c["overlaps_ci"], bool)
    ra = c["realised_auroc"]
    assert 0.0 < ra["point"] < 1.0
    lo, hi = ra["ci95"]
    assert lo <= ra["point"] <= hi
    assert ra["n_resamples"] == 5 * 30 and len(ra["per_seed"]) == 5
    assert ra["over_seeds"]["n"] == 5 and ra["over_seeds"]["ci95"] is not None
    assert c["us_bounds"]["gamma"] == 1.885 and c["us_bounds"]["auroc_lo"] == 0.55
    assert c["contains_point"] == (0.55 <= ra["point"] <= 0.75)
    mg = c["min_gamma_containing"]
    assert mg["method"] == "recomputed_from_nuisances" and mg["n_us_units"] == 120
    assert mg["gamma"] is None or (isinstance(mg["gamma"], float) and mg["gamma"] >= 1.0)


def test_analyze_gamma_comparison(analysis):
    g = analysis["gamma_comparison"]
    assert g["T_varies"] is True and g["outcome_recorded_for_T0"] is True
    assert g["us_gamma_min"] == 1.5 and g["us_odds_ratio"] == 1.885
    gm = g["gamma_min"]
    assert gm["available"] is True and gm["n_centres_used"] >= 2
    for key in ("gamma_min", "gamma_min_q95", "gamma_min_boot_lo"):
        s = gm[key]
        assert s["n"] == 5 and s["mean"] >= 1.0 and s["ci95"] is not None
    assert 0.0 <= gm["refutes_MAR_fraction"] <= 1.0
    assert set(gm["per_centre"]) == {"KC01", "KC02", "KC03", "KC04", "KC05"}
    orr = g["odds_ratio"]
    assert orr["available"] is True and orr["point"] > 0
    assert orr["ci95"][0] <= orr["point"] <= orr["ci95"][1]
    assert orr["gamma_scale_magnitude"] >= 1.0
    assert isinstance(g["gamma_min_vs_us"]["korea_ci95_contains_us"], bool)
    v = g["odds_ratio_vs_us"]
    assert isinstance(v["korea_ci95_contains_us"], bool) and isinstance(v["same_direction"], bool)
    assert v["us_odds_ratio"] == 1.885


def test_analyze_output_is_aggregate_only(analysis):
    def walk(o, path="$"):
        if isinstance(o, dict):
            assert "subject_id" not in o, path
            for k, v in o.items():
                walk(v, f"{path}.{k}")
        elif isinstance(o, list):
            assert len(o) <= 64, f"{path}: array of length {len(o)}"
            for i, v in enumerate(o):
                walk(v, f"{path}[{i}]")
    walk(analysis)


