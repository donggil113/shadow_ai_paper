def test_prepare_fixture_sidecar_and_suppression(prepared):
    with open(sidecar_of(prepared)) as f:
        side = json.load(f)
    assert side["data_source"] == "synthetic"
    assert side["schema_version"] == "1.0"
    assert len(side["input"]["sha256"]) == 64
    c = side["counts"]
    assert c["n_raw"] == 400
    assert c["n_dropped_dedup"] == 35                     # designed same-year duplicates
    assert c["n_dropped_window"] > 0
    assert c["n_final"] == c["n_raw"] - c["n_dropped_dedup"] - c["n_dropped_window"]
    assert c["n_centres"] == 5
    # the 2021 cell holds five exams -> suppressed (null + flag)
    y2021 = side["per_year"]["2021"]
    assert y2021["suppressed"] is True and y2021["n"] is None
    assert any(v["suppressed"] for v in side["per_year"].values())
    assert_suppression_rule(side)
    assert side["cohort"]["outcome_observed_all"] is True   # truth-batch cohort
    assert side["cohort"]["T_all_one"] is False             # the follow-up decision varies
    assert set(side["Z_levels"]) == {"KC01", "KC02", "KC03", "KC04", "KC05"}


def test_prepared_file_contents(prepared):
    with open(sidecar_of(prepared)) as f:
        side = json.load(f)
    df = pd.read_parquet(prepared) if str(prepared).endswith(".parquet") else pd.read_csv(prepared)
    assert len(df) == side["counts"]["n_final"] == side["prepared"]["n_rows"]
    for col in ("subject_id", "exam_date", "exam_year", "centre_id", "Z", "T", "Y_full", "Y_obs",
                "public_model_score", "followup_days"):
        assert col in df.columns
    assert not df.duplicated(["subject_id", "exam_year"]).any()       # one exam per subject-year
    assert set(df["T"].unique()) == {0, 1}
    assert df["Y_full"].notna().all()
    assert df.loc[df["T"] == 0, "Y_obs"].isna().all() and df.loc[df["T"] == 1, "Y_obs"].notna().all()
    assert (df["Z"].map(dict(enumerate(side["Z_levels"]))) == df["centre_id"]).all()
    feats = side["prepared"]["features"]
    assert feats and all(f in df.columns for f in feats)
    x = df[[f for f in feats if f.startswith("x_")]].to_numpy(float)
    assert np.allclose(x.mean(0), 0, atol=1e-8) and np.allclose(x.std(0), 1, atol=1e-6)
    assert "m_bmi" in feats and set(df["m_bmi"].unique()) <= {0.0, 1.0}
    assert "bmi" not in df.columns                                     # only standardised covariates
    # the window rule: no unit without an event has < 365 days of follow-up
    assert ((df["Y_full"] == 1) | (df["followup_days"] >= 365)).all()


def test_prepare_schema_violation_exits_3(tmp_path):
    df = pd.read_csv(FIXTURE)
    df.loc[0, "sex"] = "X"
    df.loc[1, "bmi"] = 999.0
    df.loc[2, "exam_date"] = "2019/01/01"
    df.loc[3, "followup_test_ordered"] = 1
    df.loc[3, "outcome"] = np.nan
    bad = tmp_path / "bad.csv"
    df.to_csv(bad, index=False)
    r = run(PREPARE, "--fixture", str(bad), "--out", str(tmp_path / "p.parquet"))
    assert r.returncode == 3, r.stderr
    for token in ("sex", "bmi", "exam_date", "outcome must be recorded"):
        assert token in r.stderr
    assert not (tmp_path / "p.parquet").exists() and not (tmp_path / "p.json").exists()
    # a missing required column is a schema violation too
    df2 = pd.read_csv(FIXTURE).drop(columns=["centre_id"])
    bad2 = tmp_path / "bad2.csv"
    df2.to_csv(bad2, index=False)
    r2 = run(PREPARE, "--fixture", str(bad2), "--out", str(tmp_path / "p2.parquet"))
    assert r2.returncode == 3 and "centre_id" in r2.stderr


