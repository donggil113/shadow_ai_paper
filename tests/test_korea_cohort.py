MIN_CELL = 10


def run(*args, timeout=900):
    return subprocess.run([sys.executable, *args], capture_output=True, text=True, timeout=timeout, cwd=ROOT)


def results_snapshot():
    if not os.path.isdir(RESULTS):
        return {}
    return {f: os.path.getmtime(os.path.join(RESULTS, f)) for f in os.listdir(RESULTS)}


def walk_cells(o, path="$"):
    """Yield every published count / rate dict (has a 'suppressed' key)."""
    if isinstance(o, dict):
        if "suppressed" in o and ("n" in o or "value" in o):
            yield path, o
        for k, v in o.items():
            yield from walk_cells(v, f"{path}.{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from walk_cells(v, f"{path}[{i}]")


def assert_suppression_rule(o):
    for path, c in walk_cells(o):
        if c["suppressed"]:
            assert c.get("n") is None and c.get("value") is None, path
        else:
            n = c["n"]
            assert n is not None and (n == 0 or n >= MIN_CELL), f"{path}: small cell published: {c}"


def sidecar_of(prepared):
    return os.path.splitext(str(prepared))[0] + ".json"


