def test_no_simulator_import_in_package():
    """CLAUDE.md rule 1 / spec: make_mimic_sim is never imported in this package."""
    for fn in os.listdir(PKG):
        if not fn.endswith(".py"):
            continue
        with open(os.path.join(PKG, fn)) as f:
            for line in f:
                code = line.split("#", 1)[0].strip()
                if code.startswith(("from ", "import ")):
                    assert "make_mimic_sim" not in code, (fn, code)
                    assert "..mimic" not in code and "dcl.data.mimic " not in code, (fn, code)
                assert "make_mimic_sim(" not in code, (fn, code)
    import dcl.data.mimic_ecg_echo as pkg
    assert not hasattr(pkg, "make_mimic_sim")


