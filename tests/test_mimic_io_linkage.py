def test_fixture_provenance_is_fixture(root, tables):
    assert root.source == "fixture"
    for name, (df, prov) in tables.items():
        assert prov["source"] == "fixture"
        assert prov["table"] == name
        assert os.path.isabs(prov["path"]) and os.path.isfile(prov["path"])
        assert prov["n_rows"] == len(df) and 0 < prov["n_rows"] <= 50
        assert len(prov["sha256"]) == 64 and prov["sha256_bytes"] == 1 << 20
        assert prov["columns"] == list(df.columns)
        assert set(EXPECTED_COLUMNS[name]) <= set(df.columns)
        assert (df["subject_id"] >= S).all()
    assert not root.all_real()


